package com.gamestore.repository;

import static org.junit.Assert.*;
import java.nio.file.*;
import java.sql.*;
import java.time.LocalDate;
import java.util.*;
import org.junit.*;
import com.gamestore.model.*;
import com.gamestore.util.DBConnection;

public class JdbcGameDetailsRepositoryTest {
    private static String schema; private static boolean created;
    private static Connection connection() throws SQLException, java.io.IOException, ClassNotFoundException {
        Connection conn = DBConnection.getConnection();
        try { conn.setSchema(schema); return conn; } catch (SQLException e) { conn.close(); throw e; }
    }
    private JdbcGameRepository games() { return new JdbcGameRepository(JdbcGameDetailsRepositoryTest::connection); }
    private JdbcGameDetailsRepository details() { return new JdbcGameDetailsRepository(JdbcGameDetailsRepositoryTest::connection); }
    @BeforeClass public static void setup() throws Exception {
        Assume.assumeTrue(Boolean.getBoolean("gamestore.dbTest")); schema = "gamestore_details_test_" + UUID.randomUUID().toString().replace("-", "");
        try (Connection conn = DBConnection.getConnection(); Statement stmt = conn.createStatement()) { stmt.execute("CREATE SCHEMA " + schema); created = true; }
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE games (game_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, title VARCHAR(200), price INTEGER, genre VARCHAR(50), image_url VARCHAR(500), description TEXT, is_active BOOLEAN NOT NULL DEFAULT TRUE)");
            stmt.execute(Files.readString(Path.of("sql/018_game_details.sql")));
        }
    }
    @AfterClass public static void cleanup() throws Exception {
        if (!created) { return; } if (!schema.matches("gamestore_details_test_[a-f0-9]{32}")) { throw new IllegalStateException("Unexpected schema"); }
        try (Connection conn = DBConnection.getConnection(); Statement stmt = conn.createStatement()) { stmt.execute("DROP SCHEMA " + schema + " CASCADE"); }
    }
    @Before public void reset() throws Exception {
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) {
            stmt.execute("DROP FUNCTION IF EXISTS reject_gallery() CASCADE"); stmt.execute("TRUNCATE games RESTART IDENTITY CASCADE");
        }
    }
    private GameDetails sample(String... paths) {
        return new GameDetails("小さな Studio's <b>Garden</b>", LocalDate.of(2028, 2, 29), "日本語・한국어・English", List.of(paths), "AIのイメージ\n<script>literal</script>");
    }
    private Game create(GameDetails extra) throws Exception { return games().create("Game", 2400, "Simulation", "images/moonlit_harvest.png", "Description", extra); }
    private void rejectGallery() throws Exception {
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE FUNCTION reject_gallery() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.image_path LIKE '%reject%' THEN RAISE EXCEPTION 'injected gallery error'; END IF; RETURN NEW; END $$");
            stmt.execute("CREATE TRIGGER reject_gallery BEFORE INSERT ON game_screenshots FOR EACH ROW EXECUTE FUNCTION reject_gallery()");
        }
    }
    @Test public void legacyGameAndInvalidIdentifiersHaveEmptyDetails() throws Exception {
        Game game = games().create("Legacy", 1000, "Adventure", "images/aetherbound.png");
        assertEquals(GameDetails.EMPTY, details().findForGame(game.getId()));
        for (String id : new String[] {null, "", "0", "-1", "1 OR TRUE", "999999"}) { assertEquals(GameDetails.EMPTY, details().findForGame(id)); }
    }
    @Test public void completeDetailsAndSixOrderedScreenshotsSurviveFreshRepository() throws Exception {
        var extra = sample("images/screenshots/6.png", "images/screenshots/5.png", "images/screenshots/4.png", "images/screenshots/3.png", "images/screenshots/2.png", "images/screenshots/1.png");
        Game game = create(extra); assertEquals(extra, details().findForGame(game.getId())); assertEquals("2028.02.29", extra.getFormattedReleaseDate());
        assertEquals("Description", games().findById(game.getId()).getDescription()); assertEquals(2400, games().findById(game.getId()).getPrice());
    }
    @Test public void editReordersAndRemovesImagesWithoutResumingSale() throws Exception {
        Game game = create(sample("images/screenshots/a.png", "images/screenshots/b.png", "images/screenshots/c.png")); games().setActive(game.getId(), false);
        var changed = new GameDetails("New Studio", null, "한국어", List.of("images/screenshots/c.png", "images/screenshots/a.png"), "New note");
        assertTrue(games().update(game.getId(), "Updated", 3900, "Puzzle", game.getImagePath(), "Updated description", changed));
        assertEquals(changed, details().findForGame(game.getId())); assertFalse(games().findById(game.getId()).isActive());
        assertEquals(3900, games().findById(game.getId()).getPrice());
        for (String id : new String[] {null, "-1", "bad", "99999"}) { assertFalse(games().update(id, "x", 1, "x", game.getImagePath(), "x", changed)); }
    }
    @Test public void clearingOptionalFieldsRemovesGalleryAndLegacyEditsPreserveDetails() throws Exception {
        var extra = sample("images/screenshots/a.png"); Game game = create(extra);
        games().updateDescription(game.getId(), "New description"); games().update(game.getId(), "Core only", 2000, "Adventure", game.getImagePath(), "Core description");
        assertEquals(extra, details().findForGame(game.getId()));
        games().update(game.getId(), "Cleared", 2000, "Adventure", game.getImagePath(), "", GameDetails.EMPTY);
        assertEquals(GameDetails.EMPTY, details().findForGame(game.getId()));
    }
    @Test public void screenshotFailureRollsBackNewGameAndItsMetadata() throws Exception {
        rejectGallery();
        try { create(sample("images/screenshots/first.png", "images/screenshots/reject.png")); fail("Expected gallery failure"); } catch (SQLException expected) { }
        assertTrue(games().findAll().isEmpty());
        try (Connection conn = connection(); Statement stmt = conn.createStatement(); ResultSet rows = stmt.executeQuery("SELECT (SELECT COUNT(*) FROM game_details), (SELECT COUNT(*) FROM game_screenshots)")) {
            rows.next(); assertEquals(0, rows.getInt(1)); assertEquals(0, rows.getInt(2));
        }
    }
    @Test public void screenshotFailureRollsBackCoreMetadataAndPreviouslyDeletedGallery() throws Exception {
        var original = sample("images/screenshots/old.png"); Game game = create(original); rejectGallery();
        try { games().update(game.getId(), "Wrong title", 9999, "Wrong genre", "images/aetherbound.png", "Wrong description", sample("images/screenshots/new.png", "images/screenshots/reject.png")); fail("Expected gallery failure"); }
        catch (SQLException expected) { }
        Game restored = games().findById(game.getId()); assertEquals("Game", restored.getTitle()); assertEquals(2400, restored.getPrice());
        assertEquals("Description", restored.getDescription()); assertEquals("images/moonlit_harvest.png", restored.getImagePath());
        assertEquals(original, details().findForGame(game.getId()));
    }
    @Test public void databaseRejectsUnsafePathsExcessSlotsDuplicateImagesAndInvalidMetadata() throws Exception {
        Game game = create(sample("images/screenshots/a.png"));
        List<String> bad = List.of(
            "INSERT INTO game_screenshots VALUES (" + game.getId() + ", 7, 'images/screenshots/b.png')",
            "INSERT INTO game_screenshots VALUES (" + game.getId() + ", 2, 'https://example.com/a.png')",
            "INSERT INTO game_screenshots VALUES (" + game.getId() + ", 2, 'images/screenshots/a.png')",
            "UPDATE game_details SET release_date = DATE '0001-01-01' WHERE game_id = " + game.getId(),
            "UPDATE game_details SET developer = repeat('x',101) WHERE game_id = " + game.getId());
        for (String sql : bad) {
            try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.executeUpdate(sql); fail("Expected database constraint"); } catch (SQLException expected) { }
        }
        assertEquals(1, details().findForGame(game.getId()).screenshots().size());
    }
    @Test public void repeatingMigrationsPreservesAdminChangesAndIntentionallyClearedGallery() throws Exception {
        Game game = games().create("Moonlit Harvest", 3200, "Simulation", "images/moonlit_harvest.png", "Original");
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.execute(Files.readString(Path.of("sql/019_seed_game_details.sql"))); }
        assertEquals(2, details().findForGame(game.getId()).screenshots().size());
        games().update(game.getId(), "Admin title", 7777, "Puzzle", game.getImagePath(), "Admin description", GameDetails.EMPTY);
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) {
            stmt.execute(Files.readString(Path.of("sql/018_game_details.sql"))); stmt.execute(Files.readString(Path.of("sql/019_seed_game_details.sql")));
        }
        assertEquals(GameDetails.EMPTY, details().findForGame(game.getId())); assertEquals(7777, games().findById(game.getId()).getPrice());
        assertEquals("Admin description", games().findById(game.getId()).getDescription());
    }
    @Test public void demoSeedUsesOnlyOneMatchingGameAndNeverReseedsAnEmptyProfile() throws Exception {
        Game first = games().create("Moonlit Harvest", 3200, "Simulation", "images/moonlit_harvest.png");
        Game second = games().create("Moonlit Harvest", 4000, "Simulation", "images/moonlit_harvest.png");
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.execute(Files.readString(Path.of("sql/019_seed_game_details.sql"))); }
        assertEquals(2, details().findForGame(first.getId()).screenshots().size()); assertEquals(GameDetails.EMPTY, details().findForGame(second.getId()));
        games().update(first.getId(), first.getTitle(), first.getPrice(), first.getGenre(), first.getImagePath(), "", GameDetails.EMPTY);
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.execute(Files.readString(Path.of("sql/019_seed_game_details.sql"))); }
        assertEquals(GameDetails.EMPTY, details().findForGame(first.getId())); assertEquals(GameDetails.EMPTY, details().findForGame(second.getId()));
    }
    @Test public void catalogMetadataFillsAllDemoGamesAndOnlyBlankFieldsWithoutChangingGallery() throws Exception {
        var covers = List.of("stellar_odyssey.jpg", "neon_drift.jpg", "moonlit_harvest.png", "abyssal_relay.png", "aetherbound.png", "ember_express.png",
                "lantern_post.png", "cloudberry_cafe.png", "tideglass.png", "mossbound.png", "starlight_courier.png", "fablewood_chronicles.png");
        var catalog = new ArrayList<Game>();
        for (String cover : covers) catalog.add(games().create("Renamed " + cover, 7880, "Custom genre", "images/" + cover, "My description"));
        Game moon = catalog.get(2);
        var partial = new GameDetails("My Studio", null, "My languages", List.of("images/screenshots/custom.png"), "Keep gallery note");
        games().update(moon.getId(), moon.getTitle(), moon.getPrice(), moon.getGenre(), moon.getImagePath(), moon.getDescription(), partial);
        Game unknown = games().create("Unrelated", 1234, "Other", "images/unknown.png");
        String sql = Files.readString(Path.of("sql/020_seed_catalog_metadata.sql"));
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.execute(sql); }
        var snapshots = new HashMap<String, GameDetails>();
        for (Game original : catalog) {
            var extra = details().findForGame(original.getId()); snapshots.put(original.getId(), extra);
            assertFalse(extra.developer().isBlank()); assertNotNull(extra.releaseDate()); assertFalse(extra.supportedLanguages().isBlank());
            Game current = games().findById(original.getId()); assertEquals(7880, current.getPrice()); assertEquals(original.getTitle(), current.getTitle());
            assertEquals("My description", current.getDescription()); assertEquals(original.getImagePath(), current.getImagePath());
            if (!original.getId().equals(moon.getId())) { assertTrue(extra.screenshots().isEmpty()); assertEquals("", extra.galleryNote()); }
        }
        var moonDetails = details().findForGame(moon.getId()); assertEquals("My Studio", moonDetails.developer()); assertEquals("My languages", moonDetails.supportedLanguages());
        assertEquals(LocalDate.of(2026,9,18), moonDetails.releaseDate()); assertEquals(partial.screenshots(), moonDetails.screenshots()); assertEquals(partial.galleryNote(), moonDetails.galleryNote());
        assertEquals(GameDetails.EMPTY, details().findForGame(unknown.getId()));
        try (Connection conn = connection(); Statement stmt = conn.createStatement()) { stmt.execute(sql); }
        for (var entry : snapshots.entrySet()) assertEquals(entry.getValue(), details().findForGame(entry.getKey()));
    }
}
