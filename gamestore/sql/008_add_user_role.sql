-- Run before deploying the administrator catalog feature. Does not promote any account.
BEGIN;
ALTER TABLE users ADD COLUMN IF NOT EXISTS role VARCHAR(10) NOT NULL DEFAULT 'USER'
    CHECK (role IN ('USER', 'ADMIN'));

-- The original games table has a manually assigned INTEGER primary key.
LOCK TABLE games IN ACCESS EXCLUSIVE MODE;
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'games' AND column_name = 'game_id'
          AND is_identity = 'NO' AND column_default IS NULL) THEN
        ALTER TABLE games ALTER COLUMN game_id ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;
SELECT setval(pg_get_serial_sequence('games', 'game_id'),
    GREATEST(COALESCE((SELECT MAX(game_id) FROM games), 0), 0) + 1, false);
COMMIT;
